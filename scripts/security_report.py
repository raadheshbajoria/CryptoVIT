#!/usr/bin/env python

from __future__ import annotations

import argparse
from pathlib import Path
from typing import Dict, List, Optional, Sequence

import numpy as np

PROJECT_ROOT = Path(__file__).resolve().parents[1]

SCHEMES = ["v1", "block2"]
LABELS = {"v1": "per-pixel (v1)", "block2": "block (2x2)"}


def histogram_distance(a: np.ndarray, b: np.ndarray) -> float:
    ha = np.bincount(a.ravel(), minlength=256) / a.size
    hb = np.bincount(b.ravel(), minlength=256) / b.size
    return float(0.5 * np.abs(ha - hb).sum())


def mixture_distance(plain: np.ndarray, enc: np.ndarray) -> float:
    h = np.bincount(plain.ravel(), minlength=256) / plain.size
    mixture = 0.5 * (h + h[::-1])
    he = np.bincount(enc.ravel(), minlength=256) / enc.size
    return float(0.5 * np.abs(he - mixture).sum())


def measure_scheme(
    images: Sequence[np.ndarray], scheme: str, key: str, trials: int = 5
) -> Dict[str, float]:
    from cryptovit.encryption import encrypt
    from cryptovit.evaluation.security_metrics import (
        adjacent_pixel_correlation,
        compute_entropy,
        expected_uniform_entropy,
        key_sensitivity,
        plaintext_sensitivity,
    )

    def enc(img, k):
        return encrypt(img, k, scheme=scheme)[0]

    rows: Dict[str, List[float]] = {
        k: []
        for k in (
            "entropy",
            "entropy_ref",
            "corr_plain",
            "corr_enc",
            "key_npcr",
            "key_uaci",
            "pt_npcr",
            "pt_uaci",
            "hist_tv",
            "hist_mix",
        )
    }
    for img in images:
        e = enc(img, key)
        rows["entropy"].append(compute_entropy(e)["overall"])
        rows["entropy_ref"].append(expected_uniform_entropy(img.shape[0] * img.shape[1]))
        rows["corr_plain"].append(adjacent_pixel_correlation(img)["horizontal"])
        rows["corr_enc"].append(adjacent_pixel_correlation(e)["horizontal"])
        ks = key_sensitivity(img, key, enc)
        rows["key_npcr"].append(ks["npcr"])
        rows["key_uaci"].append(ks["uaci"])
        ps = plaintext_sensitivity(img, key, enc, n_trials=trials)
        rows["pt_npcr"].append(ps["npcr"])
        rows["pt_uaci"].append(ps["uaci"])
        rows["hist_tv"].append(histogram_distance(img, e))
        rows["hist_mix"].append(mixture_distance(img, e))
    return {k: float(np.mean(v)) for k, v in rows.items()}


def build_markdown(results: Dict[str, Dict[str, float]], n_images: int) -> str:
    def row(name: str, fmt: str, key: str) -> str:
        return f"| {name} | " + " | ".join(fmt.format(results[s][key]) for s in SCHEMES) + " |"

    lines = [
        "# Security measurements",
        "",
        f"Generated by `scripts/security_report.py` on {n_images} DermaMNIST test images (28x28 RGB), "
        "averaged. These are statistical checks, **not a security proof**; neither scheme replaces a "
        "standard cipher such as AES, and the key in the code is a public research key.",
        "",
        "| Measure | " + " | ".join(LABELS[s] for s in SCHEMES) + " |",
        "|---|" + "---|" * len(SCHEMES),
        row("Entropy of the encrypted image (bits)", "{:.2f}", "entropy"),
        row("Entropy of ideal noise of this size (bits)", "{:.2f}", "entropy_ref"),
        row("Adjacent-pixel correlation, plaintext", "{:.2f}", "corr_plain"),
        row("Adjacent-pixel correlation, encrypted (0 is ideal)", "{:.2f}", "corr_enc"),
        row("Key sensitivity NPCR (%) - key differs by one bit", "{:.1f}", "key_npcr"),
        row("Key sensitivity UACI (%) - ideal about 33.5", "{:.1f}", "key_uaci"),
        row(
            "Plaintext sensitivity NPCR (%) - one pixel changed, ideal about 99.6",
            "{:.2f}",
            "pt_npcr",
        ),
        row("Plaintext sensitivity UACI (%) - ideal about 33.5", "{:.2f}", "pt_uaci"),
        row("Histogram distance plaintext vs encrypted (0 = identical)", "{:.2f}", "hist_tv"),
        row(
            "Histogram distance to the plaintext-or-inverted mixture (0 = same palette up to inversion)",
            "{:.2f}",
            "hist_mix",
        ),
        "",
        "## How to read this",
        "",
        "* A scheme with good diffusion changes about 99.6% of the output when one input pixel changes. "
        "Both schemes here change far less, so both have weak diffusion; the block scheme changes "
        "exactly one output pixel (no diffusion at all).",
        "* High key sensitivity only says the scrambling depends strongly on the key.",
        "* The block scheme inverts about half of the blocks (v -> 255 - v), so its histogram is not the "
        "plaintext histogram but a mix of it and its mirror image: the first histogram row is large for "
        "both schemes, and only the second row (distance to that mixture) shows that the block scheme "
        "keeps the original palette up to inversion while the per-pixel scheme flattens it to noise.",
        "* Adjacent-pixel correlation is high for natural images; a good cipher drives it to about 0.",
        "* The block scheme is a deliberate trade: it gives up security to stay learnable by a ViT.",
        "",
    ]
    return "\n".join(lines)


def main(argv: Optional[Sequence[str]] = None) -> int:
    p = argparse.ArgumentParser(description="Measure the encryption schemes and write SECURITY.md.")
    p.add_argument("--n", type=int, default=100, help="number of test images")
    p.add_argument("--key", default="CryptoViT_Research_Key_2025")
    p.add_argument("--out", default="docs/SECURITY.md")
    args = p.parse_args(argv)

    from cryptovit.datasets.medmnist_dataset import load_medmnist_splits

    test = load_medmnist_splits(
        "dermamnist", PROJECT_ROOT / "data/raw/medmnist", 28, download=False
    )[2]
    rng = np.random.default_rng(0)
    idx = rng.choice(len(test), size=min(args.n, len(test)), replace=False)
    images = [np.array(test[int(i)][0]) for i in idx]
    results = {s: measure_scheme(images, s, args.key) for s in SCHEMES}
    out_path = PROJECT_ROOT / args.out
    out_path.parent.mkdir(parents=True, exist_ok=True)
    out_path.write_text(build_markdown(results, len(images)), encoding="utf-8")
    print(f"Wrote {args.out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
