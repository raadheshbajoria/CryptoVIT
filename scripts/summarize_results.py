#!/usr/bin/env python
"""
scripts/summarize_results.py
=============================
Build RESULTS.md from the saved ``result_<variant>.json`` files, so every number
in the write-up comes straight from a measurement.

    python scripts/summarize_results.py
    python scripts/summarize_results.py --run "per-pixel (v1)=experiments/dermamnist" \
                                        --run "block2=experiments/dermamnist_block2"

Each ``--run LABEL=DIR`` names an encryption scheme and the experiments directory
whose ``ablation/`` folder holds its results. Variant A (plaintext) is listed once.
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path
from typing import Dict, List, Optional, Sequence, Tuple

PROJECT_ROOT = Path(__file__).resolve().parents[1]

VARIANT_LABELS = {
    "A": "Plain ViT, plaintext image",
    "B": "Plain ViT, encrypted image",
    "C": "CryptoPatchEmbedding, encrypted image",
    "D": "CryptoViT (patch embedding + key-aware positions), encrypted image",
}


def load_results(ablation_dir: Path) -> Dict[str, Dict]:
    out = {}
    for variant in VARIANT_LABELS:
        path = Path(ablation_dir) / f"result_{variant}.json"
        if path.exists():
            out[variant] = json.loads(path.read_text())
    return out


def _pct(value: Optional[float]) -> str:
    return "n/a" if value is None else f"{value * 100:.1f}%"


def _num(value: Optional[float]) -> str:
    return "n/a" if value is None else f"{value:.3f}"


def _row(scheme: str, variant: str, r: Dict, melanoma_idx: Optional[int]) -> str:
    sens = r.get("per_class_sensitivity") or []
    mel = sens[melanoma_idx] if melanoma_idx is not None and melanoma_idx < len(sens) else None
    minutes = r.get("train_time_s")
    return (
        f"| {scheme} | {variant} | {VARIANT_LABELS[variant]} | {_pct(r.get('accuracy'))} | "
        f"{_pct(r.get('balanced_accuracy'))} | {_num(r.get('auc_macro_ovr'))} | {_pct(mel)} | "
        f"{r.get('epochs_trained', '?')} | "
        f"{'n/a' if minutes is None else f'{minutes / 60:.0f}'} |"
    )


def build_markdown(runs: Sequence[Tuple[str, Dict[str, Dict]]]) -> str:
    """``runs``: (scheme label, {variant: result}) pairs, plaintext A taken from the first run."""
    class_names: List[str] = []
    for _, results in runs:
        for r in results.values():
            if r.get("class_names"):
                class_names = r["class_names"]
                break
        if class_names:
            break
    melanoma_idx = class_names.index("melanoma") if "melanoma" in class_names else None
    n_test = next((r.get("num_samples") for _, res in runs for r in res.values()), None)

    lines = [
        "# Results",
        "",
        "Generated by `scripts/summarize_results.py` from the saved `result_*.json` files; "
        "nothing here is typed by hand.",
        "",
        f"All numbers are measured once on the held-out DermaMNIST test set"
        f"{f' ({n_test} images)' if n_test else ''} with the checkpoint chosen on the validation set "
        "(best balanced accuracy). One training run (seed 42) per row.",
        "",
        "| Encryption | Variant | Model | Accuracy | Balanced accuracy | Macro AUC | "
        "Melanoma sensitivity | Epochs | Train time (min) |",
        "|---|---|---|---|---|---|---|---|---|",
    ]
    plaintext_done = False
    for scheme, results in runs:
        if "A" in results and not plaintext_done:
            lines.append(_row("none (plaintext)", "A", results["A"], melanoma_idx))
            plaintext_done = True
        for variant in ("B", "C", "D"):
            if variant in results:
                lines.append(_row(scheme, variant, results[variant], melanoma_idx))

    if class_names:
        lines += [
            "",
            "## Per-class sensitivity",
            "",
            "| Encryption | Variant | " + " | ".join(class_names) + " |",
            "|---|---|" + "---|" * len(class_names),
        ]
        plaintext_done = False
        for scheme, results in runs:
            order = [("none (plaintext)", "A")] if "A" in results and not plaintext_done else []
            plaintext_done = plaintext_done or "A" in results
            order += [(scheme, v) for v in ("B", "C", "D") if v in results]
            for label, variant in order:
                sens = results[variant].get("per_class_sensitivity") or []
                cells = [_pct(s) for s in sens] + ["n/a"] * (len(class_names) - len(sens))
                lines.append(f"| {label} | {variant} | " + " | ".join(cells) + " |")

    lines += [
        "",
        "## How to read this",
        "",
        "* Chance level for 7 balanced classes is 14.3% balanced accuracy.",
        "* Balanced accuracy is the mean of the per-class sensitivities; plain accuracy is lower "
        "for the weighted models because the loss favours the rare classes.",
        "* Rare classes have few test images (23-29), so one run's balanced accuracy can move by "
        "several points with another seed: differences of a few points are within noise.",
        "* The block scheme gives only visual protection (no diffusion, colour histogram "
        "preserved); the per-pixel scheme scrambles far more but is much harder to learn from.",
        "* Research prototype; not a medical device; not for clinical use.",
        "",
    ]
    return "\n".join(lines)


def main(argv: Optional[Sequence[str]] = None) -> int:
    p = argparse.ArgumentParser(description="Write RESULTS.md from saved results.")
    p.add_argument(
        "--run",
        action="append",
        default=None,
        metavar="LABEL=DIR",
        help="encryption label and experiments dir (repeatable)",
    )
    p.add_argument("--out", default="docs/RESULTS.md")
    args = p.parse_args(argv)

    specs = args.run or [
        "per-pixel (v1)=experiments/dermamnist",
        "block2=experiments/dermamnist_block2",
    ]
    runs = []
    for spec in specs:
        label, _, directory = spec.partition("=")
        if not directory:
            raise SystemExit(f"--run must look like LABEL=DIR, got '{spec}'")
        runs.append((label, load_results(PROJECT_ROOT / directory / "ablation")))
    out_path = PROJECT_ROOT / args.out
    out_path.parent.mkdir(parents=True, exist_ok=True)
    out_path.write_text(build_markdown(runs), encoding="utf-8")
    print(f"Wrote {args.out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
